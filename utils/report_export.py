"""
Report exporters: Markdown and a self-contained, print-ready HTML document.

All report text originates from an LLM and from third-party web pages, so the
HTML exporter escapes everything and only ever emits http(s) links.
"""

from __future__ import annotations

import html
import re
from datetime import datetime
from typing import Any, Dict, List, Optional
from urllib.parse import urlsplit

_LIST_SECTIONS = (
    ("key_findings", "Key Findings"),
    ("recommendations", "Recommendations"),
    ("risks", "Risks and Concerns"),
    ("contradictions", "Contradictions"),
    ("knowledge_gaps", "Areas for Further Research"),
)


def _format_date(iso: Optional[str]) -> str:
    try:
        return datetime.fromisoformat(iso).strftime("%d %B %Y") if iso else ""
    except ValueError:
        return ""


# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------

def report_to_markdown(report: Dict[str, Any], query: str = "",
                       created_at: Optional[str] = None) -> str:
    lines: List[str] = [f"# {report.get('title', 'Research Report')}\n"]

    byline = [part for part in (
        f"**Research question:** {query}" if query else "",
        f"**Date:** {_format_date(created_at)}" if _format_date(created_at) else "",
        f"**Confidence:** {report['confidence_level']}" if report.get("confidence_level") else "",
    ) if part]
    if byline:
        lines.append("  \n".join(byline) + "\n")

    if report.get("executive_summary"):
        lines.append(f"## Executive Summary\n{report['executive_summary']}\n")
    if report.get("summary"):
        lines.append(f"## Analysis\n{report['summary']}\n")

    for key, heading in _LIST_SECTIONS:
        if report.get(key):
            lines.append(f"## {heading}")
            lines.extend(f"- {item}" for item in report[key])
            lines.append("")

    if report.get("confidence_rationale"):
        lines.append(f"## Confidence Assessment\n{report['confidence_rationale']}\n")
    if report.get("methodology"):
        lines.append(f"## Methodology\n{report['methodology']}\n")

    if report.get("sources"):
        lines.append("## Sources")
        for src in report["sources"]:
            if isinstance(src, dict):
                cred = src.get("credibility") or 0
                lines.append(
                    f"{src.get('index', '')}. [{src.get('title', 'Unknown')}]"
                    f"({src.get('url', '')}) - Credibility: {cred:.0%}"
                )
            else:
                lines.append(f"- {src}")
        lines.append("")

    if report.get("quality_warnings"):
        lines.append("## QA Warnings")
        lines.extend(f"- {w}" for w in report["quality_warnings"])
        lines.append("")

    meta = report.get("metadata")
    if meta:
        lines.append("---")
        lines.append(
            "*Generated by Multi-Agent Deep Research System | "
            f"Iterations: {meta.get('iterations_taken', 1)} | "
            f"Replans: {meta.get('replan_count', 0)} | "
            f"Sources Scanned: {meta.get('total_sources_scanned', 0)} | "
            f"Total Searches: {meta.get('total_searches', 0)}*"
        )

    return "\n".join(lines)


