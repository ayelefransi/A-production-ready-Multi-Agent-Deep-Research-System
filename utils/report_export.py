_INLINE = re.compile(
    r"\*\*([^*]+)\*\*|\*([^*\n]+)\*|`([^`]+)`|\[([^\]]+)\]\(([^)\s]+)\)|\[(\d{1,3})\]"
)


def _safe_href(url: str) -> Optional[str]:
    try:
        parts = urlsplit(str(url))
    except ValueError:
        return None
    if parts.scheme in ("http", "https") and parts.netloc:
        return html.escape(str(url), quote=True)
    return None


def _inline(text: str) -> str:
    """Escape *text*, then apply bold/italic/code/link/citation markup."""
    out: List[str] = []
    last = 0
    for match in _INLINE.finditer(text):
        out.append(html.escape(text[last:match.start()]))
        bold, italic, code, label, url, cite = match.groups()
        if bold is not None:
            out.append(f"<strong>{html.escape(bold)}</strong>")
        elif italic is not None:
            out.append(f"<em>{html.escape(italic)}</em>")
        elif code is not None:
            out.append(f"<code>{html.escape(code)}</code>")
        elif label is not None:
            href = _safe_href(url)
            out.append(f'<a href="{href}">{html.escape(label)}</a>' if href
                       else html.escape(label))
        else:
            out.append(f'<a class="cite" href="#source-{cite}">[{cite}]</a>')
        last = match.end()
    out.append(html.escape(text[last:]))
    return "".join(out)


def _markdown_blocks(text: str) -> str:
    """Minimal block Markdown: headings, bullet/numbered lists, paragraphs."""
    out: List[str] = []
    paragraph: List[str] = []
    open_list: Optional[str] = None

    def flush_paragraph() -> None:
        if paragraph:
            out.append(f"<p>{_inline(' '.join(paragraph))}</p>")
            paragraph.clear()

    def close_list() -> None:
        nonlocal open_list
        if open_list:
            out.append(f"</{open_list}>")
            open_list = None

    for raw in (text or "").splitlines():
        line = raw.strip()
        heading = re.match(r"^(#{1,4})\s+(.*)$", line)
        bullet = re.match(r"^[-*•]\s+(.*)$", line)
        numbered = re.match(r"^\d+[.)]\s+(.*)$", line)

        if not line:
            flush_paragraph()
            close_list()
        elif heading:
            flush_paragraph()
            close_list()
            out.append(f"<h3>{_inline(heading.group(2))}</h3>")
        elif bullet or numbered:
            flush_paragraph()
            tag = "ul" if bullet else "ol"
            if open_list != tag:
                close_list()
                out.append(f"<{tag}>")
                open_list = tag
            out.append(f"<li>{_inline((bullet or numbered).group(1))}</li>")
        else:
            close_list()
            paragraph.append(line)

    flush_paragraph()
    close_list()
    return "\n".join(out)


