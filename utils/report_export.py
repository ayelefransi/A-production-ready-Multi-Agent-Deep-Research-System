def report_to_html(report: Dict[str, Any], query: str = "",
                   created_at: Optional[str] = None) -> str:
    """Render a standalone HTML document (inline CSS, no scripts, no remote assets)."""
    esc = html.escape
    title = report.get("title") or "Research Report"
    meta = report.get("metadata") or {}
    sources = [s for s in report.get("sources") or [] if isinstance(s, dict)]

    sections: List[tuple[str, str, str]] = []  # (anchor, heading, body html)

    if report.get("summary"):
        sections.append(("analysis", "Analysis", _markdown_blocks(report["summary"])))
    for key, heading in _LIST_SECTIONS:
        if report.get(key):
            tag = "ol" if key in ("key_findings", "recommendations") else "ul"
            items = "".join(f"<li>{_inline(str(item))}</li>" for item in report[key])
            sections.append((key.replace("_", "-"), heading, f"<{tag}>{items}</{tag}>"))
    if report.get("confidence_rationale"):
        level = report.get("confidence_level", "")
        lead = f"<strong>{esc(level.capitalize())} confidence.</strong> " if level else ""
        sections.append(("confidence", "Confidence Assessment",
                         f"<p>{lead}{_inline(report['confidence_rationale'])}</p>"))
    if report.get("methodology"):
        sections.append(("methodology", "Methodology", _markdown_blocks(report["methodology"])))
    if sources:
        rows = []
        for src in sources:
            index = esc(str(src.get("index", "")))
            href = _safe_href(src.get("url", ""))
            link = (f'<a href="{href}">{esc(str(src.get("url", "")))}</a>' if href
                    else esc(str(src.get("url", ""))))
            rows.append(
                f'<tr id="source-{index}"><td class="n">[{index}]</td>'
                f'<td><strong>{esc(str(src.get("title") or "Untitled source"))}</strong><br>{link}</td>'
                f'<td class="cred">{(src.get("credibility") or 0):.0%}</td></tr>'
            )
        sections.append(("sources", "Sources",
                         "<table><thead><tr><th>Ref</th><th>Source</th><th>Credibility</th></tr>"
                         f"</thead><tbody>{''.join(rows)}</tbody></table>"))

    toc = "".join(f'<li><a href="#{a}">{esc(h)}</a></li>' for a, h, _ in sections)
    body = "".join(
        f'<section id="{a}"><h2><span class="num">{i}.</span>{esc(h)}</h2>{b}</section>'
        for i, (a, h, b) in enumerate(sections, 1)
    )

    facts = [
        ("Date", _format_date(created_at)),
        ("Confidence", (report.get("confidence_level") or "").capitalize()),
        ("Sources cited", str(len(sources))),
        ("Searches run", str(meta.get("total_searches", ""))),
        ("Replanning cycles", str(meta.get("replan_count", 0))),
    ]
    facts_html = "".join(
        f"<div><dt>{esc(label)}</dt><dd>{esc(value)}</dd></div>" for label, value in facts if value
    )

    warnings = ""
    if report.get("quality_warnings"):
        items = "".join(f"<li>{_inline(str(w))}</li>" for w in report["quality_warnings"])
        warnings = (f'<div class="warn"><strong>Editor warnings.</strong> This report did not '
                    f"fully pass the automated QA gate.<ul>{items}</ul></div>")

    executive = ""
    if report.get("executive_summary"):
        executive = (f'<div class="executive"><p class="kicker">Executive summary</p>'
                     f"<p>{_inline(report['executive_summary'])}</p></div>")

    question = f'<p class="question">Research question: {esc(query)}</p>' if query else ""

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<style>{_STYLE}</style>
</head>
<body>
<main>
<p class="kicker">Research report</p>
<h1>{esc(title)}</h1>
{question}
<dl class="meta">{facts_html}</dl>
{executive}
{warnings}
<nav class="toc" aria-label="Contents"><p class="kicker">Contents</p><ol>{toc}</ol></nav>
{body}
<p class="footer">Produced by an automated multi-agent research pipeline (planner, parallel
researchers, analyst, critic, writer, editor). Citations refer to the numbered sources above.
Verify critical facts against the original sources before relying on them.</p>
</main>
</body>
</html>
"""
